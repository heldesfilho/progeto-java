package biblioteca;

public class Livro {
    String nomeLivro;
    String autorLivro;
    int quanLivro;
    int codigoLivro;
    public Livro(String nomeLivro, String autorLivro, int quanLivro, int codigoLivro){
        this.nomeLivro=nomeLivro;
        this.autorLivro=autorLivro;
        this.quanLivro=quanLivro;
        this.codigoLivro=codigoLivro;
    }
}
